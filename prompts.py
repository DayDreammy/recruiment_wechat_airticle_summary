
# 创建一个prompt类
class Prompts:
    def __init__(self):
        self.summary_prompt = summary_recruiment_prompt_short
        self.judge_prompt = judge_recruiment_prompt_short
        self.extract_recruitment_prompt = extract_recruitment_prompt
        self.article_clasify_prompt = article_classify_prompt


class PromptManager:
    def __init__(self):
        # 存储所有 prompts，按照任务类型和文章类型组织
        self.prompts = {
            "summary": {
                "general": summary_general_prompt,
                "recruitment": summary_recruiment_prompt_short_v2,
                "news": summary_news_prompt,
                "others": summary_others_prompt
            },
            "judge": {
                "recruitment": judge_recruiment_prompt_short,
            },
            "extract": {
                "recruitment": extract_recruitment_prompt,
                "general": extract_general_prompt,
                "news": extract_news_prompt,
                "others": extract_others_prompt
                # 可扩展其他类型
            },
            "classify": {
                "general": article_classify_prompt
            }
        }

    def get_prompt(self, task_type, article_type):
        """
        根据任务类型和文章类型返回对应的 prompt。
        - task_type: 任务类型 (如 'summary', 'extract', 'classify')
        - article_type: 文章类型 (如 'general', 'recruitment', 'news', 'others')
        """
        # 获取任务类型对应的 prompt 集合
        task_prompts = self.prompts.get(task_type)
        if not task_prompts:
            raise ValueError(f"未找到任务类型 '{task_type}' 的 prompts")

        # 获取对应文章类型的 prompt
        prompt = task_prompts.get(article_type, task_prompts.get("default"))
        if not prompt:
            raise ValueError(
                f"未找到任务类型 '{task_type}' 和文章类型 '{article_type}' 的 prompt")

        return prompt


